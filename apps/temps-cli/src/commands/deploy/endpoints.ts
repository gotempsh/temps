/**
 * `temps deployments` commands that map one to one onto an API operation, declared
 * as typed tables (see `src/lib/endpoint.ts`).
 */

import type { Command } from 'commander'
import {
  deleteExternalImage,
  deleteStaticBundle,
  deployFromImageUpload,
  deploymentMetricsGetLatest,
  deploymentMetricsGetRange,
  deploymentMetricsToggle,
  executeDeploymentOperation,
  getActivityGraph,
  getComposePlacement,
  getComposeStatus,
  getContainerLogs,
  getContainerLogsById,
  getDeploymentContainerLogContent,
  getDeploymentOperationStatus,
  getDeploymentOperations,
  getExternalImage,
  getLatestDeploymentMedia,
  getProjectComposeValidation,
  getRemoteExternalImage,
  getStaticBundle,
  listDeploymentContainerLogs,
  listExternalImages,
  listManagedEnvironmentVariables,
  listRemoteExternalImages,
  listStaticBundles,
  moveComposeStack,
  promoteDeployment,
  purgeAssetCache,
  purgeEnvironmentAssetCache,
  pushExternalImage,
  registerExternalImage,
  runDeploymentComposeCheck,
  tailDeploymentJobLogs,
} from '../../api/sdk.gen.js'
import { endpoint, topGroup } from '../../lib/endpoint.js'

export function registerDeployEndpoints(program: Command): void {
  const group = topGroup(program, 'deployments', "deployments")

  endpoint(group, getActivityGraph, {
    name: "get-activity-graph",
    description: "Get deployment activity graph showing daily deployment counts Similar to GitHub's contribution graph",
    query: {
      project_id: { kind: 'int', help: "Filter by project ID (optional)" },
      environment_id: { kind: 'int', help: "Filter by environment ID (optional)" },
      days: { kind: 'int', help: "Number of days to include (default: 365)" },
    },
  })

  endpoint(group, getLatestDeploymentMedia, {
    name: "get-latest-media",
    description: "Get the latest deployment URL and screenshot location for multiple projects",
    query: {
      project_ids: { kind: 'string!', help: "Comma-separated project IDs" },
    },
  })

  endpoint(group, listManagedEnvironmentVariables, {
    name: "list-managed-environment-variables",
    description: "List the environment variables generated by Temps for a deployment preset",
    query: {
      preset: { kind: 'string!', help: "Framework preset used to select public browser variable names" },
    },
  })

  endpoint(group, deploymentMetricsGetRange, {
    name: "metrics get-range",
    description: "Fetch a time-series range for a single metric on a deployment",
    path: { id: 'int' },
    query: {
      metric: { kind: 'string!', help: "Metric name, e.g. '\"pg.connections_active\"'" },
      range: { kind: 'string', help: "Time window: '\"1h\"' | '\"6h\"' | '\"24h\"' | '\"7d\"'" },
      percentile: { kind: 'number', help: "Optional histogram percentile (0–100)" },
      start_time: { kind: 'string', help: "Explicit window start (ISO 8601)" },
      end_time: { kind: 'string', help: "Explicit window end (ISO 8601)" },
    },
  })

  endpoint(group, deploymentMetricsToggle, {
    name: "metrics toggle",
    description: "Enable or disable OTLP metric ingestion for a deployment",
    path: { id: 'int' },
    body: {
      enabled: { kind: 'bool!', help: "Whether to enable ('true') or disable ('false') metric ingestion" },
      path: { kind: 'string', help: "Prometheus scrape path (optional, defaults to '/metrics')" },
      port: { kind: 'int', help: "Prometheus scrape port (optional)" },
    },
  })

  endpoint(group, deploymentMetricsGetLatest, {
    name: "metrics get-latest",
    description: "Fetch the most-recent metric values for a deployment",
    path: { id: 'int' },
  })

  endpoint(group, getComposeStatus, {
    name: "compose get-status",
    description: "The host's Docker Compose CLI, as probed at startup",
  })

  endpoint(group, purgeAssetCache, {
    name: "purge-asset-cache",
    description: "Purge all cached static assets for a project",
    path: { project_id: 'project' },
    confirm: "This will purge all cached static assets for a project.",
  })

  endpoint(group, getProjectComposeValidation, {
    name: "compose get-validation",
    description: "The project's most recent stored Compose check (from its last deployment or the revalidation after an..",
    path: { project_id: 'project' },
  })

  endpoint(group, runDeploymentComposeCheck, {
    name: "compose run-check",
    description: "Run the deploy job's Compose configuration check for a deployment, without deploying: the deployment's..",
    path: { project_id: 'project', deployment_id: 'int' },
  })

  endpoint(group, listDeploymentContainerLogs, {
    name: "list-container-logs",
    description: "List the captured (historical) container-log dumps for a deployment",
    path: { project_id: 'project', deployment_id: 'int' },
  })

  endpoint(group, getDeploymentContainerLogContent, {
    name: "get-container-log-content",
    description: "Get the captured text content of a single historical container-log dump",
    path: { project_id: 'project', deployment_id: 'int', log_id: 'int' },
  })

  endpoint(group, tailDeploymentJobLogs, {
    name: "tail-job-logs",
    description: "Tail logs for a specific deployment job in real-time via WebSocket",
    path: { project_id: 'project', deployment_id: 'int', job_id: 'string' },
    output: 'socket',
  })

  endpoint(group, getDeploymentOperations, {
    name: "get-operations",
    description: "Get all operations for a deployment",
    path: { project_id: 'project', deployment_id: 'string' },
  })

  endpoint(group, executeDeploymentOperation, {
    name: "execute-operation",
    description: "Execute a deployment operation (deploy, mark_complete, take_screenshot)",
    path: { project_id: 'project', deployment_id: 'string' },
    body: {
      operation: 'string!',
    },
  })

  endpoint(group, getDeploymentOperationStatus, {
    name: "get-operation-status",
    description: "Get the status of a specific operation type",
    path: { project_id: 'project', deployment_id: 'string', operation_type: 'string' },
  })

  endpoint(group, promoteDeployment, {
    name: "promote",
    description: "Promote a deployment to another environment",
    path: { project_id: 'project', deployment_id: 'int' },
    body: {
      target_environment_id: { kind: 'int!', help: "Target environment ID to promote the deployment to" },
    },
  })

  endpoint(group, purgeEnvironmentAssetCache, {
    name: "purge-environment-asset-cache",
    description: "Purge cached static assets for a specific environment",
    path: { project_id: 'project', environment_id: 'int' },
    confirm: "This will purge cached static assets for a specific environment.",
  })

  endpoint(group, getComposePlacement, {
    name: "compose get-placement",
    description: "Where this environment's Compose stack lives: its home node, a pending move, and whether the environment's..",
    path: { project_id: 'project', environment_id: 'int' },
  })

  endpoint(group, moveComposeStack, {
    name: "compose move-stack",
    description: "Move this environment's Compose stack to another node",
    path: { project_id: 'project', environment_id: 'int' },
    body: {
      acknowledge_data_loss: { kind: 'bool', help: "The stack starts on the new node with empty volumes; the data on its current home is kept there but not copied" },
      node_id: { kind: 'int!', help: "The node to move the stack to; '0' is the control plane" },
    },
  })

  endpoint(group, getContainerLogs, {
    name: "get-container-logs",
    description: "Get logs for a container in an environment via WebSocket",
    path: { project_id: 'project', environment_id: 'int' },
    query: {
      start_date: { kind: 'int', help: "Start date for logs" },
      end_date: { kind: 'int', help: "End date for logs" },
      tail: { kind: 'string', help: "Number of lines to tail (or 'all')" },
      container_name: { kind: 'string', help: "Optional container name (defaults to first/primary container)" },
      timestamps: { kind: 'bool', help: "Include timestamps in log output (default: false)" },
      follow: { kind: 'bool', help: "Follow log output in real-time (default: true)" },
    },
    output: 'socket',
  })

  endpoint(group, getContainerLogsById, {
    name: "get-container-logs-by-id",
    description: "Get logs for a specific container by container ID via WebSocket",
    path: { project_id: 'project', environment_id: 'int', container_id: 'string' },
    query: {
      start_date: { kind: 'int', help: "Start date for logs" },
      end_date: { kind: 'int', help: "End date for logs" },
      tail: { kind: 'string', help: "Number of lines to tail (or 'all')" },
      timestamps: { kind: 'bool', help: "Include timestamps in log output (default: false)" },
      follow: { kind: 'bool', help: "Follow log output in real-time (default: true)" },
    },
    output: 'socket',
  })

  endpoint(group, deployFromImageUpload, {
    name: "deploy-from-image-upload",
    description: "Deploy from an uploaded Docker image tarball",
    path: { project_id: 'project', environment_id: 'int' },
    query: {
      tag: { kind: 'string', help: "Deprecated display hint retained for wire compatibility" },
      health_check_path: { kind: 'string', help: "Optional HTTP health-check path override (e.g. \"/api/healthz\")" },
      upload_request_id: { kind: 'string', help: "Client-generated UUID identifying this upload attempt" },
    },
  })

  endpoint(group, listRemoteExternalImages, {
    name: "images list-remote-external",
    description: "List external images for a project",
    path: { project_id: 'project' },
    query: {
      page: { kind: 'int', help: "Page number (default: 1)" },
      page_size: { kind: 'int', help: "Items per page (default: 20)" },
    },
  })

  endpoint(group, registerExternalImage, {
    name: "images register-external",
    description: "Register an external Docker image",
    path: { project_id: 'project' },
    body: {
      digest: { kind: 'string', help: "Image digest (sha256:...)" },
      image_ref: { kind: 'string!', help: "Docker image reference (e.g., \"ghcr.io/org/app:v1.0\")" },
      metadata: { kind: 'json', help: "Additional metadata" },
      tag: { kind: 'string', help: "Image tag" },
    },
  })

  endpoint(group, deleteExternalImage, {
    name: "images delete-external",
    description: "Delete an external image",
    path: { project_id: 'project', image_id: 'int' },
    confirm: "This will delete an external image.",
  })

  endpoint(group, getRemoteExternalImage, {
    name: "images get-remote-external",
    description: "Get details of a specific external image",
    path: { project_id: 'project', image_id: 'int' },
  })

  endpoint(group, listExternalImages, {
    name: "images list-external",
    description: "List all external images for a project",
    path: { project_id: 'project' },
  })

  endpoint(group, pushExternalImage, {
    name: "images push-external",
    description: "Push an external Docker image",
    path: { project_id: 'project' },
    body: {
      image_ref: 'string!',
      metadata: 'json',
    },
  })

  endpoint(group, getExternalImage, {
    name: "images get-external",
    description: "Get details of a specific external image",
    path: { project_id: 'project', image_id: 'string' },
  })

  endpoint(group, listStaticBundles, {
    name: "static-bundles list",
    description: "List static bundles for a project",
    path: { project_id: 'project' },
    query: {
      page: { kind: 'int', help: "Page number (default: 1)" },
      page_size: { kind: 'int', help: "Items per page (default: 20)" },
    },
  })

  endpoint(group, deleteStaticBundle, {
    name: "static-bundles delete",
    description: "Delete a static bundle",
    path: { project_id: 'project', bundle_id: 'int' },
    confirm: "This will delete a static bundle.",
  })

  endpoint(group, getStaticBundle, {
    name: "static-bundles get",
    description: "Get details of a specific static bundle",
    path: { project_id: 'project', bundle_id: 'int' },
  })
}
