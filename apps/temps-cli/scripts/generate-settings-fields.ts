/**
 * Write `src/commands/settings/section-fields.gen.ts`: for every instance
 * settings section that is an object (`AppSettings.geo`, `.shield`, ...),
 * the names of its fields, read from the committed `openapi.json`.
 *
 * `settings apply` uses the list to refuse an unknown field under a section
 * the current settings cannot show (unset, `null`, or set by `--from-file`),
 * where the document itself has nothing to compare against.
 *
 * Usage: bun run scripts/generate-settings-fields.ts [--check]
 *   --check  exit 1 if the committed file differs from what would be written
 */

import { fileURLToPath } from 'node:url'

export const SPEC_FILE = fileURLToPath(new URL('../openapi.json', import.meta.url))
export const OUTPUT_FILE = fileURLToPath(new URL('../src/commands/settings/section-fields.gen.ts', import.meta.url))

type Schema = { $ref?: string; oneOf?: Schema[]; anyOf?: Schema[]; allOf?: Schema[]; properties?: Record<string, Schema> }

function resolve(schema: Schema, schemas: Record<string, Schema>, seen = new Set<string>()): Schema | undefined {
  if (schema.$ref) {
    const name = schema.$ref.replace('#/components/schemas/', '')
    if (seen.has(name)) return undefined
    seen.add(name)
    const target = schemas[name]
    return target ? resolve(target, schemas, seen) : undefined
  }
  if (schema.properties) return schema
  // `Option<Section>` is `oneOf: [{ $ref }, { type: null }]`.
  for (const branch of [...(schema.oneOf ?? []), ...(schema.anyOf ?? []), ...(schema.allOf ?? [])]) {
    const found = resolve(branch, schemas, seen)
    if (found) return found
  }
  return undefined
}

/** Section name → its field names, sorted, for every object-valued `AppSettings` field. */
export function settingsSectionFields(spec: unknown): Record<string, string[]> {
  const schemas = (spec as { components?: { schemas?: Record<string, Schema> } }).components?.schemas ?? {}
  const settings = schemas.AppSettings
  if (!settings?.properties) throw new Error('openapi.json has no AppSettings schema with properties')
  const sections: Record<string, string[]> = {}
  for (const [name, property] of Object.entries(settings.properties).sort(([a], [b]) => a.localeCompare(b))) {
    const target = resolve(property, schemas)
    if (target?.properties) sections[name] = Object.keys(target.properties).sort()
  }
  return sections
}

export function renderSectionFields(sections: Record<string, string[]>): string {
  const lines = Object.entries(sections).map(
    ([name, fields]) => `  ${name}: [${fields.map((field) => `'${field}'`).join(', ')}],`,
  )
  return `// SPDX-FileCopyrightText: 2024-2026 Temps Contributors
// SPDX-License-Identifier: MIT OR Apache-2.0

// Generated by scripts/generate-settings-fields.ts from openapi.json. Do not edit;
// run \`bun run generate:api\` (or the script) after the spec changes.

/** The fields of each object-valued instance settings section, from \`AppSettings\`. */
export const SECTION_FIELDS: Readonly<Record<string, readonly string[]>> = {
${lines.join('\n')}
}
`
}

if (import.meta.main) {
  const expected = renderSectionFields(settingsSectionFields(await Bun.file(SPEC_FILE).json()))
  if (process.argv.includes('--check')) {
    const current = (await Bun.file(OUTPUT_FILE).exists()) ? await Bun.file(OUTPUT_FILE).text() : ''
    if (current !== expected) {
      console.error(`${OUTPUT_FILE} is out of date: run bun run scripts/generate-settings-fields.ts`)
      process.exit(1)
    }
  } else {
    await Bun.write(OUTPUT_FILE, expected)
    console.log(`Wrote ${OUTPUT_FILE}`)
  }
}
