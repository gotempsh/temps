use sea_orm::entity::prelude::*;
use serde::{Deserialize, Serialize};
use temps_core::DBDateTime;

#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel, Serialize, Deserialize)]
#[sea_orm(table_name = "stateless_control_plane")]
pub struct Model {
    #[sea_orm(primary_key, auto_increment = false)]
    pub id: i32,
    pub instance_id: String,
    pub management_url: String,
    pub storage_identity: String,
    #[serde(skip_serializing)]
    pub secret_verifier: String,
    /// Random anonymous telemetry ID shared by every replica (`inst_<32 hex>`).
    /// Generated by the column default; never derived from `instance_id`.
    pub telemetry_anonymous_id: String,
    pub created_at: DBDateTime,
}

#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
pub enum Relation {}

impl ActiveModelBehavior for ActiveModel {}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serializing_the_control_plane_row_leaves_out_its_secret_verifier() {
        let row = Model {
            id: 1,
            instance_id: "inst-1".to_string(),
            management_url: "https://temps.example.com".to_string(),
            storage_identity: "storage-1".to_string(),
            secret_verifier: "stored-secret-verifier".to_string(),
            telemetry_anonymous_id: "inst_0".to_string(),
            created_at: chrono::Utc::now(),
        };

        let json = serde_json::to_string(&row).expect("serializes");

        assert!(!json.contains("stored-secret-verifier"), "{json}");
        assert!(json.contains("inst-1"), "{json}");
    }
}
