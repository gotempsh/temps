use std::collections::BTreeMap;

use serde;
use serde_json::Value;

use axum::http::{HeaderValue, StatusCode};
use axum::{
    http::header::{CONTENT_TYPE, RETRY_AFTER},
    response::IntoResponse,
    Json,
};
use serde::Serialize;

use utoipa::ToSchema;

/// Representation of a Problem error to return to the client.
/// Follows RFC 7807 - Problem Details for HTTP APIs
#[derive(Debug, Clone, Serialize, ToSchema)]
#[schema(example = json!({
    "type": "https://example.com/probs/out-of-memory",
    "title": "Internal Server Error",
    "detail": "The server encountered an unexpected condition",
    "instance": "/account/12345/msgs/abc",
    "additional_info": "Custom field with additional details"
}))]
pub struct ProblemDetails {
    /// A URI reference that identifies the problem type
    #[serde(rename = "type", skip_serializing_if = "Option::is_none")]
    #[schema(example = "https://example.com/probs/out-of-memory")]
    pub type_url: Option<String>,
    /// A short, human-readable summary of the problem type
    #[schema(example = "Internal Server Error")]
    pub title: String,
    /// HTTP status code generated by the origin server for this occurrence
    #[serde(skip_serializing_if = "Option::is_none")]
    pub status: Option<u16>,
    /// A human-readable explanation specific to this occurrence of the problem
    #[schema(example = "The server encountered an unexpected condition")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
    /// A URI reference that identifies the specific occurrence of the problem
    #[schema(example = "/account/12345/msgs/abc")]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,
    /// Additional properties of the problem
    #[serde(flatten)]
    #[schema(additional_properties = true)]
    pub extensions: BTreeMap<String, Value>,
}

/// Representation of a Problem error to return to the client.
#[derive(Debug, Clone)]
pub struct Problem {
    /// The status code of the problem.
    pub status_code: StatusCode,
    /// The actual body of the problem.
    pub body: BTreeMap<String, Value>,
    /// Internal-only metadata carried to response middleware. This is never
    /// serialized into the RFC 7807 response body.
    permission_denial: Option<PermissionDenialMarker>,
    /// Seconds sent in the `Retry-After` response header, when the client
    /// should wait before repeating the request.
    retry_after_secs: Option<u64>,
}

/// Stable authorization guard denial categories used by security auditing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PermissionDenialKind {
    InsufficientPermission,
    CrossProjectScope,
    DeploymentTokenNotAllowed,
    ProjectAccess,
    ProjectPermission,
    MissingPrincipal,
    /// A cookie-authenticated, state-changing request that did not come from
    /// the console's own origin (see [`crate::same_origin`]).
    CrossOriginRequest,
}

impl PermissionDenialKind {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::InsufficientPermission => "insufficient_permission",
            Self::CrossProjectScope => "cross_project_scope",
            Self::DeploymentTokenNotAllowed => "deployment_token_not_allowed",
            Self::ProjectAccess => "project_access",
            Self::ProjectPermission => "project_permission",
            Self::MissingPrincipal => "missing_principal",
            Self::CrossOriginRequest => "cross_origin_request",
        }
    }
}

/// A server-generated response extension proving that a 403 came from an
/// authorization guard. Its fields are intentionally private so callers can
/// inspect, but cannot forge or mutate, the marker.
#[doc(hidden)]
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PermissionDenialMarker {
    kind: PermissionDenialKind,
    required_permission: Option<String>,
}

impl PermissionDenialMarker {
    pub fn kind(&self) -> PermissionDenialKind {
        self.kind
    }

    pub fn required_permission(&self) -> Option<&str> {
        self.required_permission.as_deref()
    }
}

/// Create a new `Problem` response to send to the client.
pub fn new<S>(status_code: S) -> Problem
where
    S: Into<StatusCode>,
{
    Problem {
        status_code: status_code.into(),
        body: BTreeMap::new(),
        permission_denial: None,
        retry_after_secs: None,
    }
}

impl Problem {
    /// Mark this problem as a genuine authorization-guard denial. The marker
    /// is attached only to the resulting HTTP response extensions.
    #[doc(hidden)]
    pub fn with_permission_denial(
        mut self,
        kind: PermissionDenialKind,
        required_permission: Option<String>,
    ) -> Self {
        self.permission_denial = Some(PermissionDenialMarker {
            kind,
            required_permission,
        });
        self
    }

    /// Specify the "type" to use for the problem.
    pub fn with_type<S>(self, value: S) -> Self
    where
        S: Into<String>,
    {
        self.with_value("type", value.into())
    }

    /// Specify the "title" to use for the problem.
    pub fn with_title<S>(self, value: S) -> Self
    where
        S: Into<String>,
    {
        self.with_value("title", value.into())
    }

    /// Specify the "detail" to use for the problem.
    pub fn with_detail<S>(self, value: S) -> Self
    where
        S: Into<String>,
    {
        self.with_value("detail", value.into())
    }

    /// Specify the "instance" to use for the problem.
    pub fn with_instance<S>(self, value: S) -> Self
    where
        S: Into<String>,
    {
        self.with_value("instance", value.into())
    }

    /// Tell the client how many seconds to wait before retrying, as a
    /// `Retry-After` header. The body is unchanged: add a typed field with
    /// [`Problem::with_value`] when clients should read it from the body too.
    pub fn with_retry_after(mut self, seconds: u64) -> Self {
        self.retry_after_secs = Some(seconds);
        self
    }

    /// The `Retry-After` seconds this problem will send, if any.
    pub fn retry_after_secs(&self) -> Option<u64> {
        self.retry_after_secs
    }

    /// Specify an arbitrary value to include in the problem.
    ///
    /// # Parameters
    /// - `key` - The key for the value.
    /// - `value` - The value itself.
    pub fn with_value<V>(mut self, key: &str, value: V) -> Self
    where
        V: Into<Value>,
    {
        self.body.insert(key.to_owned(), value.into());

        self
    }
}

impl<S> From<S> for Problem
where
    S: Into<StatusCode>,
{
    fn from(status_code: S) -> Self {
        new(status_code.into())
    }
}
/// Result type where the error is always a `Problem`.
pub type Result<T> = std::result::Result<T, Problem>;

/// `type` of a problem that names none. RFC 7807 §4.2: `about:blank` says
/// the problem has no semantics beyond its HTTP status.
pub const ABOUT_BLANK_PROBLEM_TYPE: &str = "about:blank";

/// Give a problem body the members RFC 7807 expects to be meaningful when
/// present. `type` is a URI reference, so a missing or empty one becomes
/// `about:blank` (the RFC's default) instead of `""`, which a client cannot
/// dereference or match on. An empty `instance` says nothing and is left out.
fn normalize_problem_body(body: &mut BTreeMap<String, Value>) {
    let has_type = body
        .get("type")
        .and_then(Value::as_str)
        .is_some_and(|value| !value.is_empty());
    if !has_type {
        body.insert(
            "type".to_string(),
            Value::String(ABOUT_BLANK_PROBLEM_TYPE.to_string()),
        );
    }
    if body
        .get("instance")
        .and_then(Value::as_str)
        .is_some_and(str::is_empty)
    {
        body.remove("instance");
    }
}

impl IntoResponse for Problem {
    fn into_response(mut self) -> axum::response::Response {
        let mut response = if self.body.is_empty() {
            self.status_code.into_response()
        } else {
            normalize_problem_body(&mut self.body);
            let body = Json(self.body);
            let mut response = (self.status_code, body).into_response();

            response.headers_mut().insert(
                CONTENT_TYPE,
                HeaderValue::from_static("application/problem+json"),
            );
            response
        };

        if let Some(marker) = self.permission_denial {
            response.extensions_mut().insert(marker);
        }
        if let Some(seconds) = self.retry_after_secs {
            response
                .headers_mut()
                .insert(RETRY_AFTER, HeaderValue::from(seconds));
        }

        response
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::to_bytes;

    async fn body_of(problem: Problem) -> serde_json::Value {
        let response = problem.into_response();
        let bytes = to_bytes(response.into_body(), 64 * 1024).await.unwrap();
        serde_json::from_slice(&bytes).unwrap()
    }

    #[tokio::test]
    async fn a_problem_without_a_type_is_about_blank_never_an_empty_string() {
        let untyped = body_of(new(StatusCode::NOT_FOUND).with_title("Not Found")).await;
        assert_eq!(untyped["type"], ABOUT_BLANK_PROBLEM_TYPE);

        // What `ErrorBuilder::build` produced for a builder that set no type
        // or instance: `"type": ""` and `"instance": ""`.
        let empty = body_of(
            crate::error_builder::ErrorBuilder::new(StatusCode::NOT_FOUND)
                .title("Provider not found")
                .detail("Notification provider 9 not found")
                .build(),
        )
        .await;
        assert_eq!(empty["type"], ABOUT_BLANK_PROBLEM_TYPE);
        assert!(empty.get("instance").is_none(), "{empty}");
        assert_eq!(empty["detail"], "Notification provider 9 not found");
    }

    #[tokio::test]
    async fn a_problem_type_and_instance_that_were_set_are_kept() {
        let typed = body_of(
            new(StatusCode::CONFLICT)
                .with_type("https://temps.sh/probs/conflict")
                .with_instance("/projects/7"),
        )
        .await;
        assert_eq!(typed["type"], "https://temps.sh/probs/conflict");
        assert_eq!(typed["instance"], "/projects/7");
    }

    #[test]
    fn problem_schema_and_serialization_flatten_extension_members() {
        let schema =
            serde_json::to_value(<ProblemDetails as utoipa::PartialSchema>::schema()).unwrap();
        assert!(schema["properties"].get("extensions").is_none());
        assert!(!schema["required"]
            .as_array()
            .unwrap()
            .contains(&serde_json::json!("extensions")));
        let problem = ProblemDetails {
            type_url: None,
            title: "Conflict".into(),
            status: Some(409),
            detail: None,
            instance: None,
            extensions: BTreeMap::from([("code".into(), serde_json::json!("ACTOR_CHANGED"))]),
        };
        let value = serde_json::to_value(problem).unwrap();
        assert_eq!(value["code"], "ACTOR_CHANGED");
        assert!(value.get("extensions").is_none());
    }

    #[tokio::test]
    async fn permission_denial_marker_is_internal_and_preserves_body() {
        let problem = new(StatusCode::FORBIDDEN)
            .with_title("Forbidden")
            .with_value("required_permission", "users:write")
            .with_permission_denial(
                PermissionDenialKind::InsufficientPermission,
                Some("users:write".to_string()),
            );

        let response = problem.into_response();
        assert_eq!(response.status(), StatusCode::FORBIDDEN);
        let marker = response
            .extensions()
            .get::<PermissionDenialMarker>()
            .expect("guard marker should propagate through IntoResponse");
        assert_eq!(marker.kind(), PermissionDenialKind::InsufficientPermission);
        assert_eq!(marker.required_permission(), Some("users:write"));

        let body = to_bytes(response.into_body(), 1024)
            .await
            .expect("problem body should be readable");
        let json: serde_json::Value =
            serde_json::from_slice(&body).expect("problem body should remain JSON");
        assert_eq!(json["title"], "Forbidden");
        assert_eq!(json["required_permission"], "users:write");
        assert!(json.get("permission_denial").is_none());
    }

    #[test]
    fn retry_after_is_sent_as_a_header_only_when_set() {
        let response = new(StatusCode::TOO_MANY_REQUESTS)
            .with_title("Cooling down")
            .with_retry_after(17)
            .into_response();
        assert_eq!(response.status(), StatusCode::TOO_MANY_REQUESTS);
        assert_eq!(
            response
                .headers()
                .get(RETRY_AFTER)
                .and_then(|value| value.to_str().ok()),
            Some("17")
        );
        let ordinary = new(StatusCode::CONFLICT).with_title("Conflict");
        assert_eq!(ordinary.retry_after_secs(), None);
        assert!(ordinary
            .into_response()
            .headers()
            .get(RETRY_AFTER)
            .is_none());
    }

    #[test]
    fn ordinary_problem_has_no_permission_denial_marker() {
        let response = new(StatusCode::FORBIDDEN).into_response();
        assert!(response
            .extensions()
            .get::<PermissionDenialMarker>()
            .is_none());
    }
}
