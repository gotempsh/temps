    #[tokio::test]
    async fn deleting_a_route_writes_an_audit_entry_naming_it() {
        let audit = Arc::new(RecordingAuditLogger::default());
        let db = MockDatabase::new(DatabaseBackend::Postgres)
            .append_query_results([vec![stored_route("app.example.com")]])
            .append_exec_results([MockExecResult {
                last_insert_id: 0,
                rows_affected: 1,
            }])
            .append_query_results([Vec::<custom_routes::Model>::new()])
            .into_connection();
        let response = delete_route(
            State(state_with(db, audit.clone())),
            Path("app.example.com".to_string()),
            RequireAuth(AuthContext::new_session(test_user(), Role::Admin)),
            Extension(test_metadata("203.0.113.9")),
        )
        .await
        .expect("an admin may delete a route")
        .into_response();
        assert_eq!(response.status(), StatusCode::NO_CONTENT);

        let entries = audit.entries();
        assert_eq!(entries.len(), 1);
        assert_eq!(entries[0].0, "CUSTOM_ROUTE_DELETED");
        assert!(entries[0].1.contains("app.example.com"), "{}", entries[0].1);
        assert!(entries[0].1.contains("203.0.113.9"), "{}", entries[0].1);
    }

    #[tokio::test]
    async fn disabling_a_route_the_rules_would_now_refuse_is_still_allowed() {
        let audit = Arc::new(RecordingAuditLogger::default());
        let mut stored = stored_route("legacy.example.com");
        stored.host = "127.0.0.1".to_string();
        stored.enabled = false;
        let db = MockDatabase::new(DatabaseBackend::Postgres)
            .append_exec_results([MockExecResult {
                last_insert_id: 0,
                rows_affected: 1,
            }])
            .append_query_results([vec![stored.clone()]])
            .append_query_results([Vec::<custom_routes::Model>::new()])
            .into_connection();
        update_route(
            State(state_with(db, audit.clone())),
            Path("legacy.example.com".to_string()),
            RequireAuth(AuthContext::new_session(test_user(), Role::Admin)),
            Extension(test_metadata("203.0.113.9")),
            Json(UpdateRouteRequest {
                host: "127.0.0.1".to_string(),
                port: 8080,
                enabled: false,
                route_type: None,
            }),
        )
        .await
        .expect("disabling is how an operator retires an old row");
        assert_eq!(audit.entries()[0].0, "CUSTOM_ROUTE_UPDATED");
    }

