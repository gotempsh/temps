    #[tokio::test]
    async fn a_plain_user_cannot_create_update_or_delete_a_route() {
        let audit = Arc::new(RecordingAuditLogger::default());
        let state = || {
            state_with(
                MockDatabase::new(DatabaseBackend::Postgres).into_connection(),
                audit.clone(),
            )
        };
        let user = || RequireAuth(AuthContext::new_session(test_user(), Role::User));

        let created = create_route(
            State(state()),
            user(),
            Extension(test_metadata("203.0.113.9")),
            Json(create_request("app.example.com", "8.8.8.8")),
        )
        .await
        .err()
        .map(|problem| problem.status_code);
        let updated = update_route(
            State(state()),
            Path("app.example.com".to_string()),
            user(),
            Extension(test_metadata("203.0.113.9")),
            Json(UpdateRouteRequest {
                host: "8.8.8.8".to_string(),
                port: 80,
                enabled: true,
                route_type: None,
            }),
        )
        .await
        .err()
        .map(|problem| problem.status_code);
        let deleted = delete_route(
            State(state()),
            Path("app.example.com".to_string()),
            user(),
            Extension(test_metadata("203.0.113.9")),
        )
        .await
        .err()
        .map(|problem| problem.status_code);

        assert_eq!(created, Some(StatusCode::FORBIDDEN));
        assert_eq!(updated, Some(StatusCode::FORBIDDEN));
        assert_eq!(deleted, Some(StatusCode::FORBIDDEN));
        assert!(
            audit.entries().is_empty(),
            "a refused request writes no audit entry"
        );
    }

    #[tokio::test]
    async fn routes_cannot_be_written_without_signing_in() {
        let router = configure_routes().with_state(state_with(
            MockDatabase::new(DatabaseBackend::Postgres).into_connection(),
            Arc::new(RecordingAuditLogger::default()),
        ));
        for (method, uri, body) in [
            (
                "POST",
                "/lb/routes",
                r#"{"domain":"a.example.com","host":"8.8.8.8","port":80}"#,
            ),
            (
                "PUT",
                "/lb/routes/a.example.com",
                r#"{"host":"8.8.8.8","port":80,"enabled":true}"#,
            ),
            ("DELETE", "/lb/routes/a.example.com", ""),
        ] {
            let response = router
                .clone()
                .oneshot(
                    Request::builder()
                        .method(method)
                        .uri(uri)
                        .header("content-type", "application/json")
                        .body(Body::from(body))
                        .expect("request"),
                )
                .await
                .expect("response");
            assert_eq!(
                response.status(),
                StatusCode::UNAUTHORIZED,
                "{method} {uri}"
            );
        }
    }

    #[tokio::test]
    async fn an_admin_is_refused_a_loopback_or_metadata_upstream_with_a_problem_body() {
        for upstream in ["127.0.0.1", "169.254.169.254", "10.1.2.3", "localhost"] {
            let audit = Arc::new(RecordingAuditLogger::default());
            // settings, environment domains, project custom domains: all empty.
            let db = MockDatabase::new(DatabaseBackend::Postgres)
                .append_query_results([Vec::<temps_entities::settings::Model>::new()])
                .append_query_results([Vec::<temps_entities::environment_domains::Model>::new()])
                .append_query_results([Vec::<temps_entities::project_custom_domains::Model>::new()])
                .into_connection();
            let problem = create_route(
                State(state_with(db, audit.clone())),
                RequireAuth(AuthContext::new_session(test_user(), Role::Admin)),
                Extension(test_metadata("203.0.113.9")),
                Json(create_request("app.example.com", upstream)),
            )
            .await
            .err()
            .unwrap_or_else(|| panic!("{upstream} must be refused"));
            assert_eq!(problem.status_code, StatusCode::BAD_REQUEST, "{upstream}");
            assert!(
                audit.entries().is_empty(),
                "{upstream}: nothing was written"
            );
        }
    }

