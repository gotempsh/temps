/// What an audit entry records about a custom route.
#[derive(Debug, Clone, Serialize)]
struct RouteAuditDetail {
    domain: String,
    host: String,
    port: i32,
    route_type: String,
    enabled: bool,
}

impl From<&temps_entities::custom_routes::Model> for RouteAuditDetail {
    fn from(route: &temps_entities::custom_routes::Model) -> Self {
        Self {
            domain: route.domain.clone(),
            host: route.host.clone(),
            port: route.port,
            route_type: route.route_type.to_string(),
            enabled: route.enabled,
        }
    }
}

#[derive(Debug, Clone, Serialize)]
struct CustomRouteCreatedAudit {
    context: AuditContext,
    route: RouteAuditDetail,
}

#[derive(Debug, Clone, Serialize)]
struct CustomRouteUpdatedAudit {
    context: AuditContext,
    route: RouteAuditDetail,
}

#[derive(Debug, Clone, Serialize)]
struct CustomRouteDeletedAudit {
    context: AuditContext,
    route: RouteAuditDetail,
}

impl_audit_operation!(CustomRouteCreatedAudit, "CUSTOM_ROUTE_CREATED");
impl_audit_operation!(CustomRouteUpdatedAudit, "CUSTOM_ROUTE_UPDATED");
impl_audit_operation!(CustomRouteDeletedAudit, "CUSTOM_ROUTE_DELETED");

