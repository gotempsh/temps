//! Generates the migration module declarations and `Migrator::migrations()`
//! from the files in `src/migration/`, so adding a migration means adding a
//! file. The order rules live in `src/migration_order.rs`.

#![allow(
    clippy::disallowed_methods,
    reason = "build script: Cargo passes OUT_DIR only through the environment"
)]

#[path = "src/migration_order.rs"]
mod migration_order;

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs, io, process};

fn main() {
    if let Err(error) = run() {
        eprintln!("error: cannot generate the temps-migrations migration list: {error}");
        process::exit(1);
    }
}

fn io_error(action: &str, path: &Path, error: io::Error) -> String {
    format!("{action} {}: {error}", path.display())
}

fn run() -> Result<(), String> {
    let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/migration");
    println!("cargo:rerun-if-changed={}", directory.display());
    println!("cargo:rerun-if-changed=src/migration_order.rs");

    let mut migrations = Vec::new();
    let entries =
        fs::read_dir(&directory).map_err(|error| io_error("reading", &directory, error))?;
    for entry in entries {
        let entry = entry.map_err(|error| io_error("reading", &directory, error))?;
        let file_type = entry
            .file_type()
            .map_err(|error| io_error("inspecting", &entry.path(), error))?;
        let file_name = entry.file_name();
        let file_name = file_name.to_str().ok_or_else(|| {
            format!(
                "'{}' in {} is not valid UTF-8",
                file_name.to_string_lossy(),
                directory.display()
            )
        })?;
        if let Some(name) = migration_order::migration_name(file_name, file_type.is_file())
            .map_err(|error| error.to_string())?
        {
            migrations.push(name);
        }
    }

    let exceptions_path = directory.join(migration_order::EXCEPTIONS_FILE);
    let exceptions = fs::read_to_string(&exceptions_path)
        .map_err(|error| io_error("reading", &exceptions_path, error))?;
    let placements =
        migration_order::parse_exceptions(&exceptions).map_err(|error| error.to_string())?;
    let ordered =
        migration_order::order(migrations, &placements).map_err(|error| error.to_string())?;

    let out_dir = env::var_os("OUT_DIR").ok_or("Cargo did not set OUT_DIR")?;
    let output = PathBuf::from(out_dir).join("migrations.rs");
    fs::write(&output, generate(&directory, &ordered))
        .map_err(|error| io_error("writing", &output, error))
}

/// Module declarations in file-name order, then the list in run order.
fn generate(directory: &Path, ordered: &[String]) -> String {
    let mut sorted = ordered.to_vec();
    sorted.sort();
    let mut code = String::from("// Generated by build.rs from src/migration/. Do not edit.\n\n");
    for name in &sorted {
        let path = directory.join(format!("{name}.rs"));
        let _ = writeln!(
            code,
            "#[path = {:?}]\npub mod {name};",
            path.to_string_lossy()
        );
    }
    code.push_str(
        "\n/// Every migration, in the order it runs: upgrade history.\n\
         fn generated_migrations() -> Vec<Box<dyn MigrationTrait>> {\n    vec![\n",
    );
    for name in ordered {
        let _ = writeln!(code, "        Box::new({name}::Migration),");
    }
    code.push_str("    ]\n}\n");
    code
}
