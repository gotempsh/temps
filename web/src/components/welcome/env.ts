/**
 * The variables a new app starts with, as one form: what the repository's
 * `.env.example` asks for, what a database Temps creates provides, and what
 * someone pastes. Secret values never come back from the server; generated
 * ones never pass through the browser.
 */

/** Prefixes frameworks bundle into the page every visitor downloads. */
const PUBLIC_PREFIX =
  /^(NEXT_PUBLIC_|VITE_|PUBLIC_|REACT_APP_|NUXT_PUBLIC_|EXPO_PUBLIC_)/
const SECRET_NAME =
  /(SECRET|TOKEN|PASSWORD|PASSWD|PRIVATE|API_?KEY|ACCESS_KEY|_KEY$|^KEY$|DSN|CREDENTIAL|SMTP_URL|WEBHOOK)/
const SECRET_VALUE =
  /^(sk[-_](live|test|ant|proj)|sk-[A-Za-z0-9]{16,}|ghp_|github_pat_|xox[bp]-|AKIA[0-9A-Z]{12,}|-----BEGIN)/
const URL_WITH_PASSWORD = /^[a-z][a-z0-9+.-]*:\/\/[^/\s:@]+:[^/\s@]+@/i

/** Whether a value should be secret: by its name, by its shape, or a URL with a password in it. */
export function isSecret(key: string, value = ''): boolean {
  if (SECRET_VALUE.test(value) || URL_WITH_PASSWORD.test(value)) return true
  return !PUBLIC_PREFIX.test(key) && SECRET_NAME.test(key)
}

/** A secret-looking name behind a public prefix ends up in every visitor's browser. */
export function publicWarning(key: string, value = ''): string | null {
  const prefix = key.match(PUBLIC_PREFIX)?.[1]
  if (!prefix) return null
  if (SECRET_NAME.test(key.slice(prefix.length)) || SECRET_VALUE.test(value)) {
    return `${prefix} variables are sent to every visitor's browser. Is this meant to be public?`
  }
  return null
}

/** `KEY=value` lines from a pasted .env file. Comments, blanks and `export ` are handled; anything else is reported. */
export function parseDotenv(text: string): {
  vars: Array<{ key: string; value: string }>
  skipped: string[]
} {
  const vars: Array<{ key: string; value: string }> = []
  const skipped: string[] = []
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const match = line.match(
      /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/
    )
    if (!match) {
      skipped.push(line)
      continue
    }
    let value = match[2].trim()
    const quoted = value.match(/^(['"])(.*)\1$/)
    if (quoted) value = quoted[2]
    else value = value.replace(/\s+#.*$/, '')
    vars.push({ key: match[1], value })
  }
  return { vars, skipped }
}

/** Where a row's value comes from. */
export type VarSource = 'database' | 'generate' | 'you' | 'example' | 'missing'

export interface VarRow {
  key: string
  value: string
  source: VarSource
  secret: boolean
  /** One plain line: where it comes from, or what to do about it. */
  note: string
}

/** What detection says about one variable (the response's `variables`). */
export interface DetectedVar {
  key: string
  example_value?: string | null
  looks_secret?: boolean
  can_generate?: boolean
}

/**
 * The rows the form starts with. A database the app links provides some
 * names (through aliases); those are read-only. A secret Temps can make is
 * generated by default. Anything with an example value starts with it.
 */
export function initialRows(
  detected: DetectedVar[],
  provided: { label: string; names: string[] } | null
): VarRow[] {
  const fromDb = new Set(provided?.names ?? [])
  return detected.map((v): VarRow => {
    if (fromDb.has(v.key)) {
      return {
        key: v.key,
        value: '',
        source: 'database',
        secret: true,
        note: `From the new ${provided?.label}`,
      }
    }
    const secret = v.looks_secret ?? isSecret(v.key, v.example_value ?? '')
    if (v.can_generate) {
      return {
        key: v.key,
        value: '',
        source: 'generate',
        secret: true,
        note: 'A random secret Temps makes once',
      }
    }
    const example = (v.example_value ?? '').trim()
    if (example && !secret) {
      return {
        key: v.key,
        value: example,
        source: 'example',
        secret: false,
        note: 'From .env.example',
      }
    }
    return {
      key: v.key,
      value: '',
      source: 'missing',
      secret,
      note: 'Your app expects it',
    }
  })
}

/** Merge pasted values over the rows, adding any new names at the end. Database rows are never overwritten. */
export function applyPaste(
  rows: VarRow[],
  text: string
): { rows: VarRow[]; applied: number; skipped: string[] } {
  const { vars, skipped } = parseDotenv(text)
  const next = rows.map((r) => ({ ...r }))
  let applied = 0
  for (const { key, value } of vars) {
    const row = next.find((r) => r.key === key)
    if (row?.source === 'database') continue
    const updated: VarRow = {
      key,
      value,
      source: 'you',
      secret: isSecret(key, value),
      note: publicWarning(key, value) ?? 'Set by you; stored encrypted',
    }
    if (row) Object.assign(row, updated)
    else next.push(updated)
    applied++
  }
  return { rows: next, applied, skipped }
}

/** Names nobody has given a value yet. The app may still start; it is the user's call. */
export function missingKeys(rows: VarRow[]): string[] {
  return rows
    .filter((r) => r.source === 'missing' && !r.value.trim())
    .map((r) => r.key)
}

/** The variables sent with the project (typed or example values). Database and generated rows are not. */
export function typedVariables(
  rows: VarRow[]
): Array<{ key: string; value: string; is_secret: boolean }> {
  return rows
    .filter(
      (r) =>
        (r.source === 'you' ||
          r.source === 'example' ||
          r.source === 'missing') &&
        r.value.trim()
    )
    .map((r) => ({ key: r.key, value: r.value, is_secret: r.secret }))
}

/** Rows whose value the server generates after the project exists. */
export function generatedKeys(rows: VarRow[]): string[] {
  return rows.filter((r) => r.source === 'generate').map((r) => r.key)
}
